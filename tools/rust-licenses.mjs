// Writes src/licenses/rust-dependencies.txt (I-25): the Rust crates linked into the app exe, with their licenses.
// Run from the repo root after Cargo.lock changes: node tools/rust-licenses.mjs
// Uses only cargo itself: `cargo metadata` for the Windows build graph, then each crate's own LICENSE/COPYING/NOTICE files from the cargo registry.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export const TARGET = "x86_64-pc-windows-msvc";
const LICENSE_FILE = /^(licen[sc]e|copying|unlicense|notice)/i;

/** The packages the exe links: normal dependencies of the root for TARGET. Build scripts, dev dependencies and proc-macro crates (with whatever only they pull in) run at build time and never reach the exe. */
export function exeCrates(metadata) {
  const packages = new Map(metadata.packages.map((p) => [p.id, p]));
  const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set(), stack = [metadata.resolve.root];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    if (id !== metadata.resolve.root && packages.get(id).targets.some((t) => t.kind.includes("proc-macro"))) continue;
    seen.add(id);
    for (const dep of nodes.get(id).deps) if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
  }
  seen.delete(metadata.resolve.root);
  return [...seen].map((id) => packages.get(id)).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function render(crates) {
  const texts = new Map(); // license text -> crates that carry it
  const missing = [];
  for (const crate of crates) {
    const dir = dirname(crate.manifest_path);
    const files = readdirSync(dir).filter((name) => LICENSE_FILE.test(name)).sort();
    if (!files.length) missing.push(crate);
    for (const file of files) {
      const text = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").trim();
      texts.set(text, [...(texts.get(text) ?? []), `${crate.name} ${crate.version}`]);
    }
  }
  return [
    `Rust crates linked into the app (Windows ${TARGET}, normal dependencies; build-only crates left out)`,
    "Generated by tools/rust-licenses.mjs from src-tauri/Cargo.lock.",
    "",
    ...crates.map((c) => `${c.name} ${c.version}  ${c.license ?? c.license_file}`),
    "",
    ...(missing.length ? [`These crates ship no license file in their package; their license is the one named above: ${missing.map((c) => `${c.name} ${c.version}`).join(", ")}`, ""] : []),
    ...[...texts].map(([text, owners]) => `==== ${owners.join(", ")} ====\n\n${text}\n`),
  ].join("\n");
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}`) {
  const json = execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", TARGET, "--locked", "--manifest-path", "src-tauri/Cargo.toml"], { maxBuffer: 1 << 28 });
  writeFileSync("src/licenses/rust-dependencies.txt", render(exeCrates(JSON.parse(json))));
}
